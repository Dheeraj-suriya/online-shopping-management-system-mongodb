def basic_crud_queries():
    print_section("1. BASIC CRUD QUERIES")

    customer = first_customer()
    product = first_product()

    if not customer or not product:
        print("No sample data found. Run: python shopping_system.py")
        return

    # READ: Find customer by email
    print("\nCustomer by email:")
    result = db.customers.find_one({"email": customer["email"]})
    print(result)

    # READ: Find active customers
    print("\nActive customers:")
    for item in db.customers.find({"isActive": True}).limit(10):
        print(f"- {item.get('firstName', '')} {item.get('lastName', '')} | {item.get('email', '')}")

    # UPDATE: Customer preference
    db.customers.update_one(
        {"_id": customer["_id"]},
        {"$set": {"preferences.currency": "USD"}}
    )
    print("\nUpdated customer currency preference.")

    # UPDATE: Add an address only if one is not already present.
    if not any(a.get("addressId") == "demo_work_address" for a in customer.get("addresses", [])):
        db.customers.update_one(
            {"_id": customer["_id"]},
            {"$push": {"addresses": {
                "addressId": "demo_work_address",
                "type": "work",
                "street": "100 Business Ave",
                "city": "New York",
                "state": "NY",
                "zipCode": "10002",
                "country": "USA",
                "isDefault": False
            }}}
        )
        print("Added a demonstration work address.")

    # READ: Find product by SKU
    print("\nProduct by SKU:")
    print(db.products.find_one({"sku": product["sku"]}))

    # READ: Text search
    print("\nText search for 'wireless headphones':")
    for item in db.products.find({"$text": {"$search": "wireless headphones"}}):
        print(f"- {item['name']} | ${item['price']}")

    # READ: Price range
    print("\nProducts between $50 and $200:")
    for item in db.products.find({
        "price": {"$gte": 50, "$lte": 200},
        "isActive": True
    }).sort("price", ASCENDING):
        print(f"- {item['name']} | ${item['price']}")

    # UPDATE: Stock safely for demonstration, then restore it.
    original_stock = product["stock"]
    db.products.update_one(
        {"_id": product["_id"]},
        {"$inc": {"stock": -1}}
    )
    print(f"\nStock temporarily decreased: {original_stock} -> {original_stock - 1}")
    db.products.update_one(
        {"_id": product["_id"]},
        {"$inc": {"stock": 1}}
    )
    print("Stock restored after demonstration.")

    # READ: Orders for a customer
    print("\nOrders for first customer:")
    for order in db.orders.find(
        {"customerId": customer["_id"]}
    ).sort("orderDate", DESCENDING):
        print(f"- {order['orderNumber']} | {order['status']} | ${order['grandTotal']}")

    # READ: Pending orders
    print("\nPending orders:")
    for order in db.orders.find({"status": "pending"}):
        print(f"- {order['orderNumber']}")

    # UPDATE: Demonstrate order status and restore it.
    order = db.orders.find_one({"customerId": customer["_id"]})
    if order:
        old_status = order["status"]
        db.orders.update_one(
            {"_id": order["_id"]},
            {"$set": {"status": "shipped", "trackingNumber": "DEMO-TRK-123"}}
        )
        print(f"\nOrder {order['orderNumber']} status: {old_status} -> shipped")

        db.orders.update_one(
            {"_id": order["_id"]},
            {"$set": {"status": old_status}}
        )
        print(f"Order status restored to: {old_status}")


